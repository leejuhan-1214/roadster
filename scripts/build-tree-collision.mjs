import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';

// Rebuild with: node scripts/build-tree-collision.mjs
// Trunk material includes the continuous stem and substantial forks. The separate
// thin twig mesh and alpha-cutout leaves remain permeable, not solid canopy walls.
const directory=new URL('../dist/assets/trees/',import.meta.url);
const gltfBytes=await readFile(new URL('tree-small-02.gltf',directory));
const gltf=JSON.parse(gltfBytes),binary=await readFile(new URL('tree-small-02.bin',directory));
const BANDS=10, WELD_EPSILON=.0001, TINY_RADIUS=.0005;
for(const node of gltf.nodes)if(node.matrix||node.translation||node.rotation||node.scale)throw new Error('Tree transforms changed: bake node transforms before generating collision geometry.');
function accessor(index){
  const a=gltf.accessors[index],view=gltf.bufferViews[a.bufferView],components={SCALAR:1,VEC3:3}[a.type];
  if(!components||view.byteStride)throw new Error('Unexpected packed tree accessor.');
  const Typed=a.componentType===5126?Float32Array:a.componentType===5125?Uint32Array:null;
  if(!Typed)throw new Error('Unexpected tree component type.');
  return new Typed(binary.buffer,binary.byteOffset+(view.byteOffset||0)+(a.byteOffset||0),a.count*components);
}
const source=gltf.meshes[0],allPositions=source.primitives.map(p=>accessor(p.attributes.POSITION));
let minY=Infinity,maxY=-Infinity;
for(const positions of allPositions)for(let i=1;i<positions.length;i+=3){minY=Math.min(minY,positions[i]);maxY=Math.max(maxY,positions[i]);}
const height=maxY-minY,triangles=[];
for(const primitive of source.primitives){
  if(!gltf.materials[primitive.material].name.endsWith('_trunk'))continue;
  const positions=accessor(primitive.attributes.POSITION),indices=accessor(primitive.indices);
  for(let i=0;i<indices.length;i+=3)triangles.push([0,1,2].map(k=>{const n=indices[i+k]*3;return [positions[n],positions[n+1]-minY,positions[n+2]];}));
}
if(!triangles.length)throw new Error('Tree trunk material was not found.');
function clipY(poly,y,above){
  const result=[];
  for(let i=0;i<poly.length;i++){
    const a=poly[i],b=poly[(i+1)%poly.length],aInside=above?a[1]>=y:a[1]<=y,bInside=above?b[1]>=y:b[1]<=y;
    if(aInside)result.push(a);
    if(aInside!==bInside){const t=(y-a[1])/(b[1]-a[1]);result.push(a.map((v,k)=>v+(b[k]-v)*t));}
  }
  return result;
}
const cross=(a,b,c)=>(b[0]-a[0])*(c[1]-a[1])-(b[1]-a[1])*(c[0]-a[0]);
function hull(points){
  const sorted=[...new Map(points.map(p=>[p.join(','),p])).values()].sort((a,b)=>a[0]-b[0]||a[1]-b[1]);
  const half=ps=>{const h=[];for(const p of ps){while(h.length>1&&cross(h.at(-2),h.at(-1),p)<=1e-12)h.pop();h.push(p);}return h;};
  return [...half(sorted).slice(0,-1),...half([...sorted].reverse()).slice(0,-1)];
}
const area=points=>Math.abs(points.reduce((sum,p,i)=>{const q=points[(i+1)%points.length];return sum+p[0]*q[1]-q[0]*p[1];},0))*.5;
function collisionPieces(triangles,bands=BANDS){
const ys=triangles.flat().map(p=>p[1]),trunkBottom=Math.min(...ys),trunkTop=Math.max(...ys);
const pieces=[];
for(let band=0;band<bands;band++){
  const bottom=trunkBottom+band*(trunkTop-trunkBottom)/bands,top=trunkBottom+(band+1)*(trunkTop-trunkBottom)/bands;
  const polygons=triangles.map(t=>clipY(clipY(t,bottom,true),top,false)).filter(p=>p.length>=3);
  const parents=polygons.map((_,i)=>i),root=i=>parents[i]===i?i:parents[i]=root(parents[i]),seen=new Map();
  polygons.forEach((poly,index)=>poly.forEach(point=>{
    const key=point.map(v=>Math.round(v/WELD_EPSILON)).join(',');
    if(seen.has(key))parents[root(index)]=root(seen.get(key));else seen.set(key,index);
  }));
  const components=new Map();
  polygons.forEach((poly,index)=>{const key=root(index);if(!components.has(key))components.set(key,[]);components.get(key).push(...poly);});
  for(const points of components.values()){
    const low=Math.min(...points.map(p=>p[1])),high=Math.max(...points.map(p=>p[1]));
    if(high-low<1e-10)continue; // A slice boundary alone has no volume.
    const projected=points.map(p=>[p[0],p[2]]);let footprint=hull(projected);
    if(footprint.length<3||area(footprint)<1e-8){
      // Retain line-like branch tips as a millimetre-wide prism.
      footprint=hull(projected.flatMap(p=>[[p[0]-TINY_RADIUS,p[1]-TINY_RADIUS],[p[0]+TINY_RADIUS,p[1]-TINY_RADIUS],[p[0]+TINY_RADIUS,p[1]+TINY_RADIUS],[p[0]-TINY_RADIUS,p[1]+TINY_RADIUS]]));
    }
    pieces.push({bottom:low,top:high,footprint});
  }
}
return pieces;
}
const pieces=collisionPieces(triangles);
const profile={height,baseOffset:-minY,bands:BANDS,source:'Poly Haven Tree Small 02 / tree_small_02_trunk',
  geometrySha256:createHash('sha256').update(binary).digest('hex'),gltfSha256:createHash('sha256').update(gltfBytes).digest('hex'),pieces};
const output='// Generated by scripts/build-tree-collision.mjs. Do not edit by hand.\n'+
  '// Main stem and woody forks; thin twigs and leaves are permeable.\n'+
  'export const TREE_COLLISION_PROFILE='+JSON.stringify(profile)+';\n';
await writeFile(new URL('../dist/js/city-tree-profile.js',import.meta.url),output);
console.log(JSON.stringify({bands:BANDS,pieces:pieces.length,height,bytes:Buffer.byteLength(output),geometrySha256:profile.geometrySha256}));

// The six grown species use the very same near-LOD tube construction as their
// rendered model: main stem plus first-order forks with base radius >= 6 cm.
// Smaller twigs and foliage remain permeable. Profiles are generated offline;
// the map worker imports only plain profile data, never Three.js/tree growth.
const {generateTreeCollisionGeometry,TREE_SPECIES,TREE_VARIANTS}=await import('../dist/js/city-tree-species.js');
const speciesProfiles={},summary=[];
for(const species of Object.keys(TREE_SPECIES).filter(id=>!TREE_SPECIES[id].asset))for(let seed=0;seed<TREE_VARIANTS;seed++){
  const generated=generateTreeCollisionGeometry(species,seed),geometry=generated.geometry;
  const positions=geometry.getAttribute('position').array,indices=geometry.index.array,sourceTriangles=[];
  for(let i=0;i<indices.length;i+=3)sourceTriangles.push([0,1,2].map(k=>{const n=indices[i+k]*3;return [positions[n],positions[n+1],positions[n+2]];}));
  let bands=BANDS,parts=collisionPieces(sourceTriangles,bands);
  while(parts.length>50&&bands>6){bands-=2;parts=collisionPieces(sourceTriangles,bands);}
  const geometrySha256=createHash('sha256').update(new Uint8Array(positions.buffer,positions.byteOffset,positions.byteLength)).update(new Uint8Array(indices.buffer,indices.byteOffset,indices.byteLength)).digest('hex');
  speciesProfiles[species+':'+seed]={species,seed,height:generated.height,baseOffset:0,bands,source:'Roadster generated tree / main stem and first-order forks >= 0.06 m base radius',geometrySha256,pieces:parts};
  summary.push({species,seed,bands,pieces:parts.length,sourceTriangles:sourceTriangles.length});
  geometry.dispose();
}
const speciesOutput='// Generated by scripts/build-tree-collision.mjs. Do not edit by hand.\n'+
  '// Main stems and substantial forks of all 6 species x 5 visual variants.\n'+
  'export const SPECIES_COLLISION_PROFILES='+JSON.stringify(speciesProfiles)+';\n';
await writeFile(new URL('../dist/js/city-species-profiles.js',import.meta.url),speciesOutput);
console.log(JSON.stringify({profiles:summary.length,bytes:Buffer.byteLength(speciesOutput),maxPieces:Math.max(...summary.map(p=>p.pieces)),summary}));
